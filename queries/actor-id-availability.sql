WITH ev AS (
  SELECT DISTINCT TASK_ID, DATE_TRUNC('month', DATEADD(MINUTE,330,ADDED_TIME)) mth,
         TRY_PARSE_JSON(DATA):updated_by::VARCHAR ub,
         TRY_PARSE_JSON(DATA):assigned_to::VARCHAR asg,
         TRY_PARSE_JSON(DATA):title::VARCHAR title
  FROM PROD_DB.PUBLIC.TICKET_LOGS
  WHERE EVENT_NAME='TICKET_RESOLVED'
    AND DATE(DATEADD(MINUTE,330,ADDED_TIME)) BETWEEN '2026-04-01' AND '2026-09-10'
)
SELECT mth,
  COUNT(DISTINCT CASE WHEN ub='137439087976' THEN TASK_ID END) kapture_agent_all,
  COUNT(DISTINCT CASE WHEN ub='1234567890'   THEN TASK_ID END) csp_app_all,
  COUNT(DISTINCT CASE WHEN ub NOT IN ('137439087976','1234567890') THEN TASK_ID END) other_all,
  COUNT(DISTINCT CASE WHEN ub='137439087976' AND title ILIKE 'Internet Issues%' THEN TASK_ID END) kap_internet,
  COUNT(DISTINCT CASE WHEN ub='1234567890'   AND title ILIKE 'Internet Issues%' THEN TASK_ID END) csp_internet,
  COUNT(DISTINCT CASE WHEN ub NOT IN ('137439087976','1234567890') AND title ILIKE 'Internet Issues%' THEN TASK_ID END) other_internet,
  COUNT(DISTINCT TASK_ID) tickets_any
FROM ev GROUP BY 1 ORDER BY 1
